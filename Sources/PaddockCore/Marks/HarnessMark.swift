/// One CLI agent harness's official mark, kept as the single path out of the
/// vendor's own SVG rather than as a bundled image: nothing here can fail to
/// load at runtime, and the mark renders identically in the app and in the
/// offscreen chrome renders. `Resources/HarnessMarks/` holds the source files
/// and records where each came from; `HarnessMarkSourceTests` fails if this
/// path data and that file ever disagree.
public struct HarnessMark: Equatable, Sendable {
    /// The `d` attribute, verbatim.
    public let pathData: String
    /// The mark's own color, exactly as the source file fills it.
    public let ink: RGB
    /// The ground the mark is drawn on. Fixed rather than themed: OpenAI
    /// publishes the Blossom in white or black and forbids recoloring it, and
    /// paddock's chrome is light in some themes and dark in others, so the
    /// white file it ships needs a dark ground of its own everywhere.
    public let ground: RGB

    public init(pathData: String, ink: RGB, ground: RGB) {
        self.pathData = pathData
        self.ink = ink
        self.ground = ground
    }

    /// The decoded path, or `nil` if the data uses anything
    /// `VectorMarkPath` does not read -- which is what makes a mark fall back
    /// to its monogram instead of drawing a broken glyph.
    public var cgPath: CGPath? {
        VectorMarkPath.cgPath(fromSVGPathData: pathData)
    }

    public static let discGround = RGB(0, 0, 0)

    public static let claude = HarnessMark(
        pathData: CLAUDE,
        ink: RGB(0xD9, 0x77, 0x57),
        ground: discGround
    )

    public static let codex = HarnessMark(
        pathData: CODEX,
        ink: RGB(255, 255, 255),
        ground: discGround
    )
}

